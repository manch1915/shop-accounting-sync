export interface DemoProduct {
  sku: string;
  name: string;
  priceMinor: number;
  /** VAT percent, null = no VAT */
  vat: number | null;
  barcode: string | null;
  stock: number;
  /** listed in the store but not yet created in accounting: produces a mapping conflict */
  storeOnly?: boolean;
  /** created in accounting, not in the store yet: picked up by "publish new products" */
  accountingOnly?: boolean;
  /** accounting uses another article for the same item: only the barcode can link them */
  accountingSku?: string;
  /** groups variants under one store product */
  parent?: string;
  option?: string;
  /** gift cards and services: never tracked as stock */
  untracked?: boolean;
}

